# integers
num1=1000
num2=20

# ->Addition(+)
total=num1+num2
print(total)
# ->division(/)
div=num1/num2
print(div)
# ->Multiplication(*)
mult=num1*num2
print(mult)
# ->subtraction(-)
sub=num1-num2
print(sub)
# modulus(%)
x=29%5
print(x)
# floor (//)
y=29//5
print(y)
# Exponentiation
z=20**3
print(z) 

# Floats
num4=995.567

# round()
num5=round(num4,1)

print(num4)
print(num5)