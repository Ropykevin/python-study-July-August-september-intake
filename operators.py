# Operators 
# =>used to perfom programming operations
        # categories of operators 
# 1.Arithmetic operators->used for calculations (+,**,*,/,%,//,-)

# 2.Comparison operators->used to compare values or variables(==,>,<,>=,<=,!=)
# return Booleans
print(10!=11)

# Logical operators =>used to combine conditions
# and->returns True when all conditions are true 
print(10<20 and 250<500)
# or ->returns true if one of the conditions is met
print(10 > 20 or 250 <500)
# Not reverses the result
print(not 10<5)

# Assignment Operators->used to assign values to Variables(=,+=,-=,*=,/=)
x=20
y=30
x=x+y
print(x)

